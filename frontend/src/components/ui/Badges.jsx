import { CATEGORY_COLORS, UNCLASSIFIED, APPROVAL_LABELS } from '../../utils/constants'
import Icon from './Icon'

const slug = (s) => s.toLowerCase().replace(/\s+/g, '-')

export function StatusBadge({ status }) {
  return <span className={`badge status-${slug(status)}`}>{status}</span>
}

export function PriorityBadge({ priority }) {
  return (
    <span className={`badge priority-${slug(priority)}`}>
      {priority === 'Urgent' && <Icon name="alert" size={12} />}
      {priority}
    </span>
  )
}

export function CategoryBadge({ category }) {
  const name = category || UNCLASSIFIED
  return (
    <span className="category-tag">
      <span className="category-dot" style={{ background: CATEGORY_COLORS[name] }} aria-hidden="true" />
      {name}
    </span>
  )
}

/** Marks anything an AI (or the demo engine) produced. Demo output is never shown as live. */
export function AiBadge({ mode = 'demo' }) {
  return (
    <span className={`ai-badge ai-${mode}`} title={mode === 'demo' ? 'Sample output from the demo engine, not a live AI model' : 'Generated by an AI model'}>
      <Icon name="sparkles" size={12} />
      {mode === 'demo' ? 'AI-generated · Demo output' : 'AI-generated'}
    </span>
  )
}

export function ApprovalBadge({ status }) {
  return <span className={`badge approval-${status}`}>{APPROVAL_LABELS[status] || status}</span>
}
